"""Recreate local RGB machine-code inputs from the hash-pinned official updater.

Output contains vendor-owned material and is NOT covered by this script's GPL.
Never execute the downloaded Windows updater. Only extract its known byte range.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path

from target import ORIGINAL_SHA256, UPDATER_SHA256, STOCK_NAME

RANGES = [(0x266, 0x2820), (0x2850, 0x2860), (0x30a8, 0x315e),
          (0x3374, 0x3378), (0x42bc, 0x45b2)]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def extract(updater):
    data = Path(updater).read_bytes()
    if digest(data) != UPDATER_SHA256:
        raise ValueError("Unrecognized Ducky updater. Extraction refused.")
    firmware = data[0x1a9f70:0x1a9f70 + 43746]
    if digest(firmware) != ORIGINAL_SHA256:
        raise ValueError("Extracted original image hash mismatch.")
    return firmware


def engine_ram(firmware):
    from unicorn import Uc, UC_ARCH_ARM, UC_MODE_THUMB, UC_MODE_MCLASS
    from unicorn.arm_const import UC_ARM_REG_SP, UC_ARM_REG_PC, UC_ARM_REG_R4, UC_ARM_REG_LR
    u = Uc(UC_ARCH_ARM, UC_MODE_THUMB | UC_MODE_MCLASS)
    u.mem_map(0, 0x20000)
    u.mem_write(0, firmware)
    u.mem_map(0x20000000, 0x10000)
    u.reg_write(UC_ARM_REG_SP, 0x20000830)

    def run(start, end, count):
        u.emu_start(start | 1, end, count=count)
        if u.reg_read(UC_ARM_REG_PC) != end:
            raise RuntimeError(f"Initialization did not reach 0x{end:x}")

    run(0xa7cc, 0x9196, 2000000)
    base = bytes(u.mem_read(0x20000000, 0x5000))
    u.reg_write(UC_ARM_REG_SP, 0x2000f000)
    u.reg_write(UC_ARM_REG_R4, 0)
    run(0x94b8, 0x954e, 10000)
    u.mem_write(0x20002b8f, struct.pack("<H", 0x4f10))
    u.reg_write(UC_ARM_REG_LR, 0xff01)
    run(0xc6, 0x232, 200000)
    for address in (0x247c, 0x242a):
        u.reg_write(UC_ARM_REG_SP, 0x2000f000)
        u.reg_write(UC_ARM_REG_LR, 0xff01)
        run(address, 0xff00, 200000)
    return base, bytes(u.mem_read(0x20000000, 0x5000))


def generate(firmware, ram, destination):
    from capstone import Cs, CS_ARCH_ARM, CS_MODE_THUMB, CS_MODE_MCLASS
    from capstone.arm import ARM_INS_LDR, ARM_OP_MEM, ARM_REG_PC
    dis = Cs(CS_ARCH_ARM, CS_MODE_THUMB | CS_MODE_MCLASS)
    dis.detail = True
    dis.skipdata = True
    pools = set()
    for ins in dis.disasm(firmware, 0):
        if ins.id == ARM_INS_LDR and len(ins.operands) > 1:
            operand = ins.operands[1]
            if operand.type == ARM_OP_MEM and operand.mem.base == ARM_REG_PC:
                pools.add(((ins.address + 4) & ~3) + operand.mem.disp)
    lines = ["/* Locally extracted Ducky V1.16 machine code. Vendor rights reserved.",
             " * Generated by tools/generate_vendor.py; not GPL source. */",
             ".syntax unified", ".cpu cortex-m0", ".thumb",
             '.section .text.ducky_stock_blob,"ax",%progbits', ".balign 4",
             ".global ducky_stock_blob", "ducky_stock_blob:"]
    relocations = []
    for start, end in RANGES:
        lines.append(f".org 0x{start:x}")
        i = start
        while i < end:
            value = struct.unpack_from("<I", firmware, i)[0] if i % 4 == 0 and i + 4 <= end else 0
            expr = None
            if i in pools:
                if 0x20001754 <= value < 0x20002e78:
                    expr = f"ducky_stock_ram + {value - 0x20001754}"
                elif 0x200003a0 <= value < 0x2000042c:
                    expr = f"ducky_stock_rng + {value - 0x200003a0}"
                elif 0x20000000 <= value < 0x20005000:
                    expr = "0 /* excluded non-engine RAM */"
            if expr is not None:
                lines.append(".word " + expr)
                relocations.append([i, value])
                i += 4
            else:
                lines.append(f".byte 0x{firmware[i]:02x}")
                i += 1
    if len(relocations) != 68:
        raise RuntimeError(f"Expected 68 reviewed relocations, got {len(relocations)}")
    lines += [".org 0x48ec", "bx lr", ".size ducky_stock_blob, .-ducky_stock_blob",
              '.section .note.GNU-stack,"",%progbits']
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "ducky_stock_blob.S").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (destination / "ducky_stock_initial.inc").write_text(
        "\n".join(f"[{i}]=0x{v:02x}," for i, v in enumerate(ram[0x1754:0x2e78]) if v) + "\n", encoding="utf-8")
    return {"ranges": RANGES, "ram_relocations": relocations, "stub": 0x48ec}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("updater", type=Path)
    parser.add_argument("output", type=Path, help="Private build directory")
    args = parser.parse_args()
    firmware = extract(args.updater)
    base, ram = engine_ram(firmware)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / STOCK_NAME).write_bytes(firmware)
    (args.output / "stock-initial-ram.bin").write_bytes(base)
    (args.output / "stock-engine-initial.bin").write_bytes(ram)
    result = generate(firmware, ram, args.output / "generated")
    (args.output / "relocations.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    print("Verified original firmware and regenerated 68 RGB relocations.")


if __name__ == "__main__":
    main()
